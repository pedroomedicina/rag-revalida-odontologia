#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Sequence

from dotenv import load_dotenv

load_dotenv()


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build/update hybrid retrieval index in Postgres (pgvector + FTS)."
    )
    parser.add_argument(
        "--chunks-jsonl",
        type=Path,
        default=Path("data/processed/chunks.jsonl"),
        help="Path to chunks.jsonl generated by chunker.py",
    )
    parser.add_argument(
        "--dsn",
        default=os.getenv("DATABASE_URL", ""),
        help="Postgres DSN (or set DATABASE_URL)",
    )
    parser.add_argument(
        "--table",
        default="rag_chunks",
        help="Target Postgres table name (default: rag_chunks)",
    )
    parser.add_argument(
        "--embedding-model",
        default="intfloat/multilingual-e5-base",
        help="SentenceTransformer model name",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=32,
        help="Embedding/upsert batch size",
    )
    parser.add_argument(
        "--max-chunks",
        type=int,
        default=0,
        help="Optional cap for quick tests (0 = all chunks)",
    )
    return parser


@dataclass
class ChunkRecord:
    chunk_id: str
    doc_id: str
    title: str
    filename: str
    page_start: int
    page_end: int
    section_title: str
    content_type: str
    ocr_quality: str
    extraction_method: str
    token_estimate: int
    text: str


def validate_table_name(table: str) -> str:
    if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", table):
        raise ValueError(f"Invalid table name: {table}")
    return table


def load_chunks(path: Path, max_chunks: int) -> List[ChunkRecord]:
    records: List[ChunkRecord] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            payload = json.loads(line)
            record = ChunkRecord(
                chunk_id=str(payload.get("chunk_id", "")).strip(),
                doc_id=str(payload.get("doc_id", "")).strip(),
                title=str(payload.get("title", "")),
                filename=str(payload.get("filename", "")),
                page_start=int(payload.get("page_start", 0) or 0),
                page_end=int(payload.get("page_end", 0) or 0),
                section_title=str(payload.get("section_title", "")),
                content_type=str(payload.get("content_type", "")),
                ocr_quality=str(payload.get("ocr_quality", "")),
                extraction_method=str(payload.get("extraction_method", "")),
                token_estimate=int(payload.get("token_estimate", 0) or 0),
                text=str(payload.get("text", "")),
            )
            if not record.chunk_id or not record.doc_id or not record.text.strip():
                continue
            records.append(record)
            if max_chunks > 0 and len(records) >= max_chunks:
                break
    return records


def batched(items: Sequence[ChunkRecord], batch_size: int) -> Iterable[Sequence[ChunkRecord]]:
    for start in range(0, len(items), batch_size):
        yield items[start : start + batch_size]


def to_vector_literal(values: Sequence[float]) -> str:
    return "[" + ",".join(f"{value:.8f}" for value in values) + "]"


def ensure_schema(cursor, table: str, embedding_dim: int) -> None:
    cursor.execute("CREATE EXTENSION IF NOT EXISTS vector;")
    cursor.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {table} (
            chunk_id TEXT PRIMARY KEY,
            doc_id TEXT NOT NULL,
            title TEXT NOT NULL,
            filename TEXT NOT NULL,
            page_start INTEGER NOT NULL,
            page_end INTEGER NOT NULL,
            section_title TEXT NOT NULL,
            content_type TEXT NOT NULL,
            ocr_quality TEXT NOT NULL,
            extraction_method TEXT NOT NULL,
            token_estimate INTEGER NOT NULL,
            text TEXT NOT NULL,
            embedding VECTOR({embedding_dim}) NOT NULL,
            search_tsv tsvector GENERATED ALWAYS AS (
                to_tsvector(
                    'spanish',
                    coalesce(title, '') || ' ' ||
                    coalesce(section_title, '') || ' ' ||
                    coalesce(text, '')
                )
            ) STORED
        );
        """
    )
    cursor.execute(
        f"CREATE INDEX IF NOT EXISTS {table}_embedding_ivfflat_idx ON {table} USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);"
    )
    cursor.execute(
        f"CREATE INDEX IF NOT EXISTS {table}_search_tsv_gin_idx ON {table} USING gin (search_tsv);"
    )
    cursor.execute(
        f"CREATE INDEX IF NOT EXISTS {table}_doc_id_idx ON {table} (doc_id);"
    )


def upsert_batch(cursor, table: str, records: Sequence[ChunkRecord], vectors: Sequence[Sequence[float]]) -> None:
    sql = f"""
        INSERT INTO {table} (
            chunk_id, doc_id, title, filename, page_start, page_end, section_title,
            content_type, ocr_quality, extraction_method, token_estimate, text, embedding
        ) VALUES (
            %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s::vector
        )
        ON CONFLICT (chunk_id) DO UPDATE SET
            doc_id = EXCLUDED.doc_id,
            title = EXCLUDED.title,
            filename = EXCLUDED.filename,
            page_start = EXCLUDED.page_start,
            page_end = EXCLUDED.page_end,
            section_title = EXCLUDED.section_title,
            content_type = EXCLUDED.content_type,
            ocr_quality = EXCLUDED.ocr_quality,
            extraction_method = EXCLUDED.extraction_method,
            token_estimate = EXCLUDED.token_estimate,
            text = EXCLUDED.text,
            embedding = EXCLUDED.embedding;
    """
    params = []
    for record, vector in zip(records, vectors):
        params.append(
            (
                record.chunk_id,
                record.doc_id,
                record.title,
                record.filename,
                record.page_start,
                record.page_end,
                record.section_title,
                record.content_type,
                record.ocr_quality,
                record.extraction_method,
                record.token_estimate,
                record.text,
                to_vector_literal(vector),
            )
        )
    cursor.executemany(sql, params)


def main() -> int:
    args = build_parser().parse_args()
    table = validate_table_name(args.table)
    chunks_path = args.chunks_jsonl.expanduser().resolve()

    if not chunks_path.exists():
        raise SystemExit(f"chunks.jsonl not found: {chunks_path}")
    if not args.dsn:
        raise SystemExit("Missing --dsn and DATABASE_URL is not set.")
    if args.batch_size < 1:
        raise SystemExit("batch-size must be >= 1")

    records = load_chunks(chunks_path, max_chunks=max(args.max_chunks, 0))
    if not records:
        raise SystemExit("No valid chunk rows found in chunks JSONL.")

    try:
        import psycopg  # type: ignore
    except Exception as exc:
        raise SystemExit("Install psycopg first: pip install 'psycopg[binary]'") from exc

    try:
        from sentence_transformers import SentenceTransformer  # type: ignore
    except Exception as exc:
        raise SystemExit("Install sentence-transformers first: pip install sentence-transformers") from exc

    model = SentenceTransformer(args.embedding_model)
    probe_vector = model.encode([records[0].text], normalize_embeddings=True)[0]
    embedding_dim = int(len(probe_vector))

    with psycopg.connect(args.dsn) as conn:
        with conn.cursor() as cursor:
            ensure_schema(cursor, table=table, embedding_dim=embedding_dim)
        conn.commit()

        total = len(records)
        upserted = 0
        for batch in batched(records, args.batch_size):
            texts = [record.text for record in batch]
            vectors = model.encode(
                texts,
                batch_size=args.batch_size,
                normalize_embeddings=True,
            )
            vectors_as_lists: List[List[float]] = [list(map(float, vector)) for vector in vectors]
            with conn.cursor() as cursor:
                upsert_batch(cursor, table=table, records=batch, vectors=vectors_as_lists)
            conn.commit()
            upserted += len(batch)
            print(f"Upserted {upserted}/{total} chunks")

    print("Done.")
    print(f"Table: {table}")
    print(f"Embedding model: {args.embedding_model}")
    print(f"Embedding dimension: {embedding_dim}")
    print(f"Chunks processed: {len(records)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
