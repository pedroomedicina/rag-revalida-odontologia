#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

from rag.text_search import TS_CONFIG, ensure_search_column, ensure_text_search_config


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build/update hybrid retrieval index in Postgres (pgvector + FTS)."
    )
    parser.add_argument(
        "--chunks-jsonl",
        type=Path,
        default=Path("data/processed/chunks.jsonl"),
        help="Path to chunks.jsonl generated by chunker.py",
    )
    parser.add_argument(
        "--dsn",
        default=os.getenv("DATABASE_URL", ""),
        help="Postgres DSN (or set DATABASE_URL)",
    )
    parser.add_argument(
        "--table",
        default="rag_chunks",
        help="Target Postgres table name (default: rag_chunks)",
    )
    parser.add_argument(
        "--embedding-model",
        default="intfloat/multilingual-e5-base",
        help="SentenceTransformer model name",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=32,
        help="Embedding/upsert batch size",
    )
    parser.add_argument(
        "--max-chunks",
        type=int,
        default=0,
        help=(
            "Optional cap for quick tests (0 = all chunks). Documents it touches are fully "
            "replaced by the capped rows."
        ),
    )
    parser.add_argument(
        "--prune",
        action="store_true",
        help="Also delete rows whose doc_id is not in the chunks file (documents removed "
        "from the corpus). Not allowed with --max-chunks.",
    )
    return parser


@dataclass
class ChunkRecord:
    chunk_id: str
    doc_id: str
    title: str
    filename: str
    page_start: int
    page_end: int
    section_title: str
    content_type: str
    ocr_quality: str
    extraction_method: str
    token_estimate: int
    text: str


def validate_table_name(table: str) -> str:
    if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", table):
        raise ValueError(f"Invalid table name: {table}")
    return table


def load_chunks(path: Path, max_chunks: int) -> list[ChunkRecord]:
    records: list[ChunkRecord] = []
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            payload = json.loads(line)
            record = ChunkRecord(
                chunk_id=str(payload.get("chunk_id", "")).strip(),
                doc_id=str(payload.get("doc_id", "")).strip(),
                title=str(payload.get("title", "")),
                filename=str(payload.get("filename", "")),
                page_start=int(payload.get("page_start", 0) or 0),
                page_end=int(payload.get("page_end", 0) or 0),
                section_title=str(payload.get("section_title", "")),
                content_type=str(payload.get("content_type", "")),
                ocr_quality=str(payload.get("ocr_quality", "")),
                extraction_method=str(payload.get("extraction_method", "")),
                token_estimate=int(payload.get("token_estimate", 0) or 0),
                text=str(payload.get("text", "")),
            )
            if not record.chunk_id or not record.doc_id or not record.text.strip():
                continue
            records.append(record)
            if max_chunks > 0 and len(records) >= max_chunks:
                break
    return records


def batched(items: Sequence[ChunkRecord], batch_size: int) -> Iterable[Sequence[ChunkRecord]]:
    for start in range(0, len(items), batch_size):
        yield items[start : start + batch_size]


def to_vector_literal(values: Sequence[float]) -> str:
    return "[" + ",".join(f"{value:.8f}" for value in values) + "]"


def ensure_schema(cursor, table: str, embedding_dim: int) -> None:
    cursor.execute("CREATE EXTENSION IF NOT EXISTS vector;")
    ensure_text_search_config(cursor)
    cursor.execute(
        f"""
        CREATE TABLE IF NOT EXISTS {table} (
            chunk_id TEXT PRIMARY KEY,
            doc_id TEXT NOT NULL,
            title TEXT NOT NULL,
            filename TEXT NOT NULL,
            page_start INTEGER NOT NULL,
            page_end INTEGER NOT NULL,
            section_title TEXT NOT NULL,
            content_type TEXT NOT NULL,
            ocr_quality TEXT NOT NULL,
            extraction_method TEXT NOT NULL,
            token_estimate INTEGER NOT NULL,
            text TEXT NOT NULL,
            embedding VECTOR({embedding_dim}) NOT NULL
        );
        """
    )
    # Adds search_tsv on new tables and migrates tables built with the old `spanish` config.
    if ensure_search_column(cursor, table):
        print(f"search_tsv (re)built with the {TS_CONFIG} text search config")
    cursor.execute(
        f"CREATE INDEX IF NOT EXISTS {table}_embedding_ivfflat_idx ON {table} "
        "USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);"
    )
    cursor.execute(f"CREATE INDEX IF NOT EXISTS {table}_doc_id_idx ON {table} (doc_id);")


def upsert_batch(
    cursor, table: str, records: Sequence[ChunkRecord], vectors: Sequence[Sequence[float]]
) -> None:
    sql = f"""
        INSERT INTO {table} (
            chunk_id, doc_id, title, filename, page_start, page_end, section_title,
            content_type, ocr_quality, extraction_method, token_estimate, text, embedding
        ) VALUES (
            %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s::vector
        )
        ON CONFLICT (chunk_id) DO UPDATE SET
            doc_id = EXCLUDED.doc_id,
            title = EXCLUDED.title,
            filename = EXCLUDED.filename,
            page_start = EXCLUDED.page_start,
            page_end = EXCLUDED.page_end,
            section_title = EXCLUDED.section_title,
            content_type = EXCLUDED.content_type,
            ocr_quality = EXCLUDED.ocr_quality,
            extraction_method = EXCLUDED.extraction_method,
            token_estimate = EXCLUDED.token_estimate,
            text = EXCLUDED.text,
            embedding = EXCLUDED.embedding;
    """
    params = []
    for record, vector in zip(records, vectors, strict=True):
        params.append(
            (
                record.chunk_id,
                record.doc_id,
                record.title,
                record.filename,
                record.page_start,
                record.page_end,
                record.section_title,
                record.content_type,
                record.ocr_quality,
                record.extraction_method,
                record.token_estimate,
                record.text,
                to_vector_literal(vector),
            )
        )
    cursor.executemany(sql, params)


def replace_chunks(
    cursor,
    table: str,
    records: Sequence[ChunkRecord],
    vectors: Sequence[Sequence[float]],
    prune: bool = False,
) -> dict[str, int]:
    """Make the table hold exactly these chunks for every document they belong to.

    Chunk IDs are positional (`<doc_id>-ch-0001`), so re-chunking a document can leave
    old IDs behind; upserting alone never removes them. All existing rows of each doc_id
    in `records` are deleted first, then the new rows are inserted. With prune=True,
    rows of documents absent from `records` are deleted too.

    Run inside one transaction so readers never see a document half-replaced.
    """
    doc_ids = sorted({record.doc_id for record in records})
    cursor.execute(f"DELETE FROM {table} WHERE doc_id = ANY(%s)", (doc_ids,))
    replaced = cursor.rowcount
    pruned = 0
    if prune:
        cursor.execute(f"DELETE FROM {table} WHERE NOT (doc_id = ANY(%s))", (doc_ids,))
        pruned = cursor.rowcount
    upsert_batch(cursor, table=table, records=records, vectors=vectors)
    return {
        "documents": len(doc_ids),
        "deleted_rows": replaced,
        "pruned_rows": pruned,
        "inserted_rows": len(records),
    }


def main() -> int:
    load_dotenv()
    args = build_parser().parse_args()
    table = validate_table_name(args.table)
    chunks_path = args.chunks_jsonl.expanduser().resolve()

    if not chunks_path.exists():
        raise SystemExit(f"chunks.jsonl not found: {chunks_path}")
    if not args.dsn:
        raise SystemExit("Missing --dsn and DATABASE_URL is not set.")
    if args.batch_size < 1:
        raise SystemExit("batch-size must be >= 1")
    if args.prune and args.max_chunks > 0:
        raise SystemExit("--prune with --max-chunks would delete documents past the cap.")

    records = load_chunks(chunks_path, max_chunks=max(args.max_chunks, 0))
    if not records:
        raise SystemExit("No valid chunk rows found in chunks JSONL.")

    try:
        import psycopg  # type: ignore
    except Exception as exc:
        raise SystemExit("Install psycopg first: pip install 'psycopg[binary]'") from exc

    try:
        from sentence_transformers import SentenceTransformer  # type: ignore
    except Exception as exc:
        raise SystemExit(
            "Install sentence-transformers first: pip install sentence-transformers"
        ) from exc

    model = SentenceTransformer(args.embedding_model)
    probe_vector = model.encode([records[0].text], normalize_embeddings=True)[0]
    embedding_dim = int(len(probe_vector))

    total = len(records)
    vectors_as_lists: list[list[float]] = []
    for batch in batched(records, args.batch_size):
        vectors = model.encode(
            [record.text for record in batch],
            batch_size=args.batch_size,
            normalize_embeddings=True,
        )
        vectors_as_lists.extend(list(map(float, vector)) for vector in vectors)
        print(f"Embedded {len(vectors_as_lists)}/{total} chunks")

    with psycopg.connect(args.dsn) as conn:
        with conn.cursor() as cursor:
            ensure_schema(cursor, table=table, embedding_dim=embedding_dim)
        conn.commit()

        # Delete + insert in one transaction: no window where a document is missing.
        with conn.cursor() as cursor:
            counts = replace_chunks(
                cursor, table=table, records=records, vectors=vectors_as_lists, prune=args.prune
            )
        conn.commit()

    print(
        f"Replaced {counts['documents']} documents: deleted {counts['deleted_rows']} old rows, "
        f"inserted {counts['inserted_rows']}, pruned {counts['pruned_rows']}."
    )
    print("Done.")
    print(f"Table: {table}")
    print(f"Embedding model: {args.embedding_model}")
    print(f"Embedding dimension: {embedding_dim}")
    print(f"Chunks processed: {len(records)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
